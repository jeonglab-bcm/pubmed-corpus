"""REPORT.md: what each route contributed, what the audit and screen removed, and recall.

Generated offline from ``out/`` and the decision files; byte-identical for
identical inputs, so ``report --check`` can run in CI.
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict

from . import corpus as corpus_mod
from . import mentions as mentions_mod
from . import query as query_mod
from .project import Project, pmid_key, read_tsv

SAMPLE = 15


def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "n/a"


def _icite_status(seed: dict) -> str:
    if seed["icite_found"] != "1":
        return "**no**"
    return "yes" if int(seed["references"] or 0) + int(seed["cited_by"] or 0) else "yes, **no links yet**"


def _table(header: list[str], rows: list[list]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]
    return out


def build(project: Project) -> str:
    out = project.out
    corpus = read_tsv(corpus_mod._need(out / "corpus.tsv", "assemble"))
    excluded = read_tsv(out / "excluded.tsv")
    manifest = json.loads((out / "manifest.json").read_text())
    meta = {r["pmid"]: r for r in read_tsv(out / "metadata.tsv")}
    clauses = project.clauses()
    hits = corpus_mod.load_query_hits(project)
    log = project.run_log()
    in_corpus = {r["pmid"]: r for r in corpus}
    refs = project.reference_sets()

    L = [f"# Corpus report: {project.config['name']}", "",
         "Generated by `pubmed-corpus report` from `out/` and the decision files. Do not edit.", ""]

    # -- summary ----------------------------------------------------------
    L += ["## Summary", ""]
    counts = manifest["counts"]
    L += _table(["Tier", "Papers", "How a paper gets in"], [
        ["seed", counts.get("seed", 0), "one of the seed papers"],
        ["core", counts.get("core", 0), "an approved PubMed clause (title, abstract or MeSH)"],
        ["fulltext", counts.get("fulltext", 0), "PubTator tags the disease with an approved wording; not in the core"],
        ["expansion", counts.get("expansion", 0), "reached only from the seeds, kept by the relevance screen"],
        ["**total**", f"**{counts.get('total', 0)}**", ""],
    ])
    if manifest["excluded"]:
        L += ["", "Excluded: " + ", ".join(f"{n} {k}" for k, n in manifest["excluded"].items()) + " (`out/excluded.tsv`)."]
    L += ["", "Steps run: " + ", ".join(f"{s} {log[s]['date']}" for s in ("terms", "query", "pubtator", "expand", "metadata")
                                     if s in log) + "."]
    if "pubtator" in log:
        L += [f"PubTator release: `{log['pubtator']['url'].rsplit('/', 1)[-1]}`, Last-Modified {log['pubtator']['last_modified']}."]

    # -- query ------------------------------------------------------------
    L += ["", "## PubMed query", ""]
    approved = {c["id"] for c in clauses if c["status"] == "approved"}
    core = set(query_mod.core(hits, clauses))
    owners: dict[str, set[str]] = defaultdict(set)
    for cid in approved:
        for p in hits.get(cid, []):
            owners[p].add(cid)
    ref_union = set().union(*refs.values()) if refs else set()
    rows = []
    for c in clauses:
        if c["status"] == "rejected":
            rows.append([f"`{c['id']}`", "rejected", "", "", ""])
            continue
        ids = set(hits.get(c["id"], []))
        if c["status"] == "approved":
            only = sum(1 for p in ids if owners[p] == {c["id"]})
        else:
            only = len(ids - core)
        rows.append([f"`{c['id']}`", c["status"], len(ids), only, len(ids & ref_union) if refs else ""])
    L += _table(["Clause", "Status", "Hits", "Only this clause*", "In reference"], rows)
    L += ["", "*For an approved clause: papers no other approved clause retrieves. For a proposed clause: papers it would add "
              "to the core.", ""]
    for c in clauses:
        L += [f"- `{c['id']}` ({c['status']}): `{c['query']}`" + (f" — {c['rationale'].strip()}" if c.get("rationale") else "")]

    # -- pubtator ---------------------------------------------------------
    rows_pt = corpus_mod.load_pubtator(project)
    if rows_pt:
        rules = mentions_mod.Rules.load(project.mentions_file)
        audit = mentions_mod.audit(rows_pt, rules, core)
        approved_pt = mentions_mod.approved_papers(rows_pt, rules)
        tagged = {r["pmid"] for r in rows_pt}
        L += ["", "## PubTator full-text tier", ""]
        L += _table(["", "Papers"], [
            [f"Tagged with {', '.join(project.concepts)}", len(tagged)],
            ["...with at least one approved wording", len(approved_pt)],
            ["...of those, already in the core", len(set(approved_pt) & core)],
            ["...outside the core (full-text tier before exclusions)", len(set(approved_pt) - core)],
            ["...with no approved wording (dropped)", len(tagged - set(approved_pt))],
        ])
        rejected = [a for a in audit if a["decision"] == mentions_mod.REJECT][:SAMPLE]
        if rejected:
            L += ["", "Most frequent rejected wordings (papers carrying the wording):", ""]
            L += _table(["Wording", "Papers", "Outside core"], [[a["wording"], a["papers"], a["papers_outside_core"]] for a in rejected])
        appr = [a for a in audit if a["decision"] == mentions_mod.APPROVE][:SAMPLE]
        if appr:
            L += ["", "Most frequent approved wordings:", ""]
            L += _table(["Wording", "Papers", "Outside core"], [[a["wording"], a["papers"], a["papers_outside_core"]] for a in appr])
        tail = [a for a in audit if a["decision"] in (mentions_mod.UNDECIDED, mentions_mod.CONFLICT)]
        L += ["", f"Undecided wordings below the {rules.min_papers_to_decide}-paper threshold: {len(tail)} "
                  f"(treated as rejected; {sum(a['papers'] for a in tail)} paper-wording pairs)."]

    # -- expansion --------------------------------------------------------
    seeds_path = out / "expansion_seeds.tsv"
    if seeds_path.exists():
        L += ["", "## Seed expansion", ""]
        L += _table(["Seed", "PMID", "In iCite", "References", "Cited by", "Related"],
                    [[s["key"], s["seed"], _icite_status(s), s["references"], s["cited_by"], s["related"]]
                     for s in read_tsv(seeds_path)])
        cands = corpus_mod.candidates(project)
        reached = {e["pmid"] for e in read_tsv(out / "expansion.tsv")}
        tiers = Counter(cands[p]["tier"] for p in reached if p in cands)
        decisions = corpus_mod.load_decisions(project)
        todo = corpus_mod.needs_screen(cands)
        dec = Counter(("rule" if decisions[p]["screener"] == "rule" else decisions[p]["decision"]) if p in decisions else "none"
                      for p in todo)
        L += ["", f"{len(reached)} papers reached; {tiers.get('core', 0)} already in the core, {tiers.get('fulltext', 0)} in the "
                  f"full-text tier, {tiers.get('seed', 0)} seeds, {len(todo)} reached only from the seeds.",
              f"Screen of those {len(todo)}: {dec.get('rule', 0)} included by rule (disease wording in title/abstract), "
              f"{dec.get('include', 0)} included and {dec.get('exclude', 0)} excluded by the agent, {dec.get('none', 0)} not screened."]
        screened_out = [e for e in excluded if e["reason"].startswith("screened out")][:SAMPLE]
        if screened_out:
            L += ["", "Screened out (first by PMID):", ""]
            L += _table(["PMID", "Title", "Reason"], [[e["pmid"], e["title"][:90], e["reason"][len("screened out: "):]]
                                                     for e in screened_out])

    # -- reference --------------------------------------------------------
    for name, ref in refs.items():
        L += ["", f"## Against the reference: {name}", ""]
        desc = next((r.get("description", "") for r in project.config.get("references") or [] if r.get("name") == name), "")
        if desc:
            L += [desc.strip(), ""]
        cum, rows = set(), []
        for tier in corpus_mod.TIERS:
            cum |= {p for p, r in in_corpus.items() if r["tier"] == tier}
            rows.append([f"+ {tier}" if rows else tier, len(cum & ref), _pct(len(cum & ref), len(ref))])
        L += _table(["Corpus up to tier", "Reference papers found", "Recall"], rows)
        missed = sorted(ref - set(in_corpus), key=pmid_key)
        no_abs = sum(1 for p in missed if meta.get(p, {}).get("has_abstract") == "0")
        gone = sum(1 for p in missed if meta.get(p, {}).get("missing") == "1")
        excl = {e["pmid"]: e["reason"] for e in excluded}
        L += ["", f"Reference size {len(ref)}. Missed: {len(missed)} ({no_abs} without an abstract, {gone} no longer in PubMed, "
                  f"{sum(1 for p in missed if p in excl)} reached but excluded)."]
        proposed = [c["id"] for c in clauses if c["status"] == "proposed"]
        for cid in proposed:
            n = len(set(hits.get(cid, [])) & set(missed))
            L += [f"Proposed clause `{cid}` would recover {n} of them."]
        if missed:
            L += ["", "Missed reference papers (first by PMID):", ""]
            L += _table(["PMID", "Year", "Title"], [[p, meta.get(p, {}).get("year", ""), meta.get(p, {}).get("title", "")[:100]]
                                                   for p in missed[:SAMPLE]])
        extra = Counter(r["tier"] for p, r in in_corpus.items() if p not in ref)
        L += ["", "Corpus papers not in the reference, by tier: "
              + ", ".join(f"{t} {extra.get(t, 0)}" for t in corpus_mod.TIERS) + "."]
    return "\n".join(L) + "\n"
